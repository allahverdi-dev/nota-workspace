const CATALOGUES = { en, az };

export const LANGUAGES = Object.freeze([
  { code: 'en', label: 'English' },
  { code: 'az', label: 'Azərbaycanca' },
]);

let current = 'en';

/** @param {string} code */
export function setLanguage(code) {
  current = CATALOGUES[code] ? code : 'en';
  document.documentElement.lang = current;
  return current;
}


/** BCP-47 tag for Intl formatting. */
export function getLocale() {
  return current === 'az' ? 'az-AZ' : 'en-US';
}

/**
 * Look up a message and interpolate `{name}` placeholders.
 * Pass `count` to select the `_one` variant automatically.
 *
 * @param {string} key
 * @param {Record<string, string | number>} [params]
 */
export function t(key, params) {
  let lookupKey = key;
  if (params && Number(params.count) === 1 && (CATALOGUES[current][`${key}_one`] || en[`${key}_one`])) {
    lookupKey = `${key}_one`;
  }

  const template = CATALOGUES[current]?.[lookupKey] ?? en[lookupKey] ?? en[key] ?? key;
  if (!params) return template;

  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  );
}
